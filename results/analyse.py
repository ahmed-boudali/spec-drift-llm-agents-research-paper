#!/usr/bin/env python3
"""
analyse.py -- aggregate scored runs into the tables reported in the paper.

Emits both a console summary and LaTeX table bodies, so the numbers in the
paper are generated from the run files rather than transcribed by hand.

Usage:
    python analyse.py --runs C1.jsonl C3.jsonl --latex ../paper/tables.tex
"""

from __future__ import annotations

import argparse
import json
import math
from collections import defaultdict
from pathlib import Path


def load(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.open(encoding="utf-8")]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score interval -- correct for proportions near 0 or 1, where the
    normal approximation gives impossible bounds."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - m), min(1.0, c + m))


def mcnemar(a: list[dict], b: list[dict]) -> tuple[int, int, float | None]:
    """Exact McNemar on paired per-item correctness."""
    ka = {r["id"]: r.get("attribution") == "correct" for r in a}
    kb = {r["id"]: r.get("attribution") == "correct" for r in b}
    shared = set(ka) & set(kb)
    b01 = sum(1 for i in shared if not ka[i] and kb[i])   # fixed by B
    b10 = sum(1 for i in shared if ka[i] and not kb[i])   # broken by B
    n = b01 + b10
    if n == 0:
        return b01, b10, None
    # two-sided exact binomial
    tail = sum(math.comb(n, k) for k in range(0, min(b01, b10) + 1)) / (2 ** n)
    return b01, b10, min(1.0, 2 * tail)


def summarise(name: str, rows: list[dict]) -> dict:
    total = len(rows)
    att = defaultdict(int)
    for r in rows:
        att[r.get("attribution", r.get("outcome", "?"))] += 1

    by_strat: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in rows:
        strat = "control" if r["provenance"] == "control" else (
            "tour" if r["provenance"] == "tour_seeded" else r["layer"])
        by_strat[strat][r.get("attribution", "?")] += 1
        by_strat[strat]["n"] += 1

    layers = {}
    for k in ("V1", "V2", "V3", "V4"):
        vals = [r[k] for r in rows if k in r]
        layers[k] = (sum(vals), len(vals))

    scored = [r for r in rows if "precision" in r]
    return {
        "name": name, "total": total, "attribution": dict(att),
        "by_stratum": {k: dict(v) for k, v in by_strat.items()},
        "layers": layers,
        "precision": sum(r["precision"] for r in scored) / len(scored) if scored else 0,
        "recall": sum(r["recall"] for r in scored) / len(scored) if scored else 0,
        "exact": sum(1 for r in scored if r["exact_match"]) / len(scored) if scored else 0,
    }


def report(s: dict) -> None:
    n = s["total"]
    print("=" * 70)
    print(f"{s['name']}   n = {n}")
    print("=" * 70)

    att = s["attribution"]
    correct = att.get("correct", 0)
    failures = n - correct - att.get("api_error", 0)
    lo, hi = wilson(correct, n)
    print(f"\ncorrect        {correct:4d} / {n}  = {correct/n:6.1%}"
          f"   [{lo:.1%}, {hi:.1%}]")
    print(f"failures       {failures:4d}")
    for k in ("F_drift", "F_gap", "F_model", "api_error"):
        if att.get(k):
            share = att[k] / failures if failures else 0
            print(f"  {k:10s} {att[k]:4d}   ({share:5.1%} of failures)")

    if failures:
        fd = att.get("F_drift", 0)
        lo, hi = wilson(fd, failures)
        print(f"\nH2: F_drift / F = {fd/failures:.1%}  [{lo:.1%}, {hi:.1%}]"
              f"   threshold 20% -> {'MET' if fd/failures >= 0.20 else 'NOT met'}")

    print("\nper-layer validity")
    for k, (ok, tot) in s["layers"].items():
        if tot:
            print(f"  {k}  {ok}/{tot} = {ok/tot:6.1%}")

    print("\nby stratum")
    for strat, d in sorted(s["by_stratum"].items()):
        m = d.get("n", 0)
        c = d.get("correct", 0)
        print(f"  {strat:10s} n={m:4d}  correct {c/m:6.1%}"
              f"  F_drift={d.get('F_drift',0):3d}"
              f"  F_gap={d.get('F_gap',0):3d}  F_model={d.get('F_model',0):3d}")

    print(f"\nsequence  precision {s['precision']:.3f}"
          f"  recall {s['recall']:.3f}  exact {s['exact']:.1%}")


def latex(summaries: list[dict], pairs, out: Path) -> None:
    L = []
    L.append("% Generated by results/analyse.py -- do not edit by hand.")
    L.append("% Regenerate: python analyse.py --runs C1.jsonl C3.jsonl --latex ../paper/tables.tex")
    L.append("")
    L.append("\\newcommand{\\resultsGenerated}{" +
             __import__("datetime").date.today().isoformat() + "}")
    L.append("")

    for s in summaries:
        n, att = s["total"], s["attribution"]
        correct = att.get("correct", 0)
        failures = n - correct - att.get("api_error", 0)
        tag = s["name"].replace(".jsonl", "")
        L.append(f"\\newcommand{{\\{tag}N}}{{{n}}}")
        L.append(f"\\newcommand{{\\{tag}Correct}}{{{correct}}}")
        L.append(f"\\newcommand{{\\{tag}CorrectPct}}{{{correct/n*100:.1f}}}")
        L.append(f"\\newcommand{{\\{tag}Failures}}{{{failures}}}")
        for k in ("F_drift", "F_gap", "F_model"):
            key = k.replace("_", "")
            L.append(f"\\newcommand{{\\{tag}{key}}}{{{att.get(k,0)}}}")
        if failures:
            L.append(f"\\newcommand{{\\{tag}DriftShare}}"
                     f"{{{att.get('F_drift',0)/failures*100:.1f}}}")
        L.append("")

    for (a, b, b01, b10, p) in pairs:
        ta, tb = a.replace(".jsonl", ""), b.replace(".jsonl", "")
        L.append(f"\\newcommand{{\\mcnemar{ta}{tb}Fixed}}{{{b01}}}")
        L.append(f"\\newcommand{{\\mcnemar{ta}{tb}Broken}}{{{b10}}}")
        L.append(f"\\newcommand{{\\mcnemar{ta}{tb}P}}"
                 f"{{{'{:.4f}'.format(p) if p is not None else 'n/a'}}}")
        L.append("")

    out.write_text("\n".join(L), encoding="utf-8")
    print(f"\nwrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", nargs="+", type=Path, required=True)
    ap.add_argument("--latex", type=Path, default=None)
    args = ap.parse_args()

    data = {p.name: load(p) for p in args.runs}
    summaries = [summarise(n, rows) for n, rows in data.items()]
    for s in summaries:
        report(s)
        print()

    pairs = []
    names = list(data)
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            a, b = names[i], names[j]
            b01, b10, p = mcnemar(data[a], data[b])
            pairs.append((a, b, b01, b10, p))
            print("=" * 70)
            print(f"McNemar  {a} vs {b}")
            print(f"  {b} fixes {b01} that {a} failed")
            print(f"  {b} breaks {b10} that {a} passed")
            print(f"  exact two-sided p = {p if p is not None else 'n/a (no discordant pairs)'}")

    if args.latex:
        latex(summaries, pairs, args.latex)


if __name__ == "__main__":
    main()
